/* 零依赖构建：把 src/ 分片按序号拼成 Obsidian 可加载的单文件 main.js
 * 用法：node build.mjs          仅构建到 dist/
 *       node build.mjs --deploy 构建 + 备份现网 + 部署到插件目录
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, "src");
const DIST = path.join(ROOT, "dist");
const PLUGIN_DIR = "C:/Users/33880/Documents/my-note/.obsidian/plugins/grid-diary";
const BACKUP_ROOT = "C:/Users/33880/Documents/_plugin_backups/grid-diary";

const files = fs.readdirSync(SRC).filter((f) => /^\d{2}-.+\.js$/.test(f)).sort();
if (!files.length) throw new Error("src/ 下没有找到源码分片");
const VERSION = JSON.parse(fs.readFileSync(path.join(ROOT, "manifest.json"), "utf8")).version;
const banner = `/* Grid Diary v${VERSION} - built from src/ by build.mjs - DO NOT EDIT THIS FILE DIRECTLY */\n`;
const code = banner + files.map((f) => `/* ---- ${f} ---- */\n` + fs.readFileSync(path.join(SRC, f), "utf8")).join("\n\n");

// 语法校验（只解析，不执行）
try { new vm.Script(code, { filename: "main.js" }); }
catch (e) { console.error("✗ 语法错误：", e.message); process.exit(1); }

fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, "main.js"), code, "utf8");
for (const f of ["styles.css", "manifest.json"]) {
  fs.copyFileSync(path.join(ROOT, f), path.join(DIST, f));
}
console.log(`✓ 构建完成：${files.length} 个分片 → dist/main.js (${(code.length / 1024).toFixed(1)} KB)`);
console.log("✓ 语法校验通过");

if (process.argv.includes("--deploy")) {
  if (!fs.existsSync(PLUGIN_DIR)) throw new Error("插件目录不存在：" + PLUGIN_DIR);
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  const stamp = `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`;
  const bak = path.join(BACKUP_ROOT, `v2-deploy-${stamp}`);
  fs.mkdirSync(bak, { recursive: true });
  for (const f of fs.readdirSync(PLUGIN_DIR)) {
    const from = path.join(PLUGIN_DIR, f);
    if (fs.statSync(from).isFile()) fs.copyFileSync(from, path.join(bak, f));
  }
  console.log(`✓ 部署前备份：${bak}`);
  for (const f of ["main.js", "styles.css", "manifest.json"]) {
    fs.copyFileSync(path.join(DIST, f), path.join(PLUGIN_DIR, f));
  }
  console.log(`✓ 已部署到 ${PLUGIN_DIR}（data.json 保留，由插件自动迁移）`);
}
